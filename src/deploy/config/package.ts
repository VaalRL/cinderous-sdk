function packageJson(config: DeployConfig, dependency: string | undefined, worker: boolean): string {
  const name = `${config.name ?? DEFAULT_WORKER_NAME}-deploy`;
  const pkg: Record<string, unknown> = { name, private: true, type: 'module' };
  if (worker) {
    pkg.scripts = { deploy: 'wrangler deploy', 'dry-run': 'wrangler deploy --dry-run', dev: 'wrangler dev' };
    if (dependency !== undefined) pkg.dependencies = { '@cinderous/client': dependency };
    pkg.devDependencies = { wrangler: '^4' };
  } else if (dependency !== undefined) {
    pkg.dependencies = { '@cinderous/client': dependency };
  }
  return `${JSON.stringify(pkg, null, 2)}\n`;
}

function workerEntry(sdkVersion: string, selfContained: boolean): string {
  const lines = [...header('//', sdkVersion)];
  if (selfContained) {
    lines.push(
      "import { setRelayVersion } from './relay.mjs';",
      '',
      `setRelayVersion(${JSON.stringify(sdkVersion)});`,
      `export { default, ${RELAY_DO_BINDING.className} } from './relay.mjs';`,
    );
  } else {
    lines.push(
      "import { setRelayVersion } from '@cinderous/client/relay';",
      '',
      '// NIP-11 `version`（部署者的版號；預設是產生部署包的 SDK 版號）',
      `setRelayVersion(${JSON.stringify(sdkVersion)});`,
      "export { default } from '@cinderous/client/relay/worker';",
      "export * from '@cinderous/client/relay/worker';",
    );
  }
  lines.push('');
  return lines.join('\n');
}


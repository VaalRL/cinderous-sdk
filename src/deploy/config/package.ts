/**
 * 產生部署包（SDK ADR 0050 §5）。先驗證設定（有錯就丟例外，列出全部錯誤）；回傳的內容不含絕對路徑與秘密值，
 * 同一份設定與 ctx → 同一組檔案（逐位元組相同），可以提交、可以 diff。
 */
export function renderDeployPackage(config: DeployConfig, ctx: DeployPackageContext): DeployPackage {
  assertDeployConfig(config, { sdkVersion: ctx.sdkVersion });
  const host = hostOfTarget(config.target);
  const worker = host === 'worker';
  const selfContained = worker && ctx.selfContained === true;
  if (ctx.selfContained === true && !worker) throw new Error('--self-contained 只適用於 Workers 目標（cloudflare、cloudflare-api）');
  const push = serviceOfConfig(config) === 'push-gateway';
  if (ctx.selfContained === true && push) throw new Error('--self-contained 只適用於中繼：推播閘道的部署包以相依（或內嵌的 sdk/）引用 SDK');
  if (selfContained && !ctx.relayWorkerSource) throw new Error('selfContained 需要 relayWorkerSource（預打包的中繼 Worker）');
  const source = ctx.sdkSource ?? { kind: 'embed' };
  const embed = !selfContained && source.kind === 'embed';
  const dependency = selfContained ? undefined : source.kind === 'spec' ? source.spec : 'file:./sdk';
  const v = ctx.sdkVersion;
  const name = config.name ?? DEFAULT_WORKER_NAME;
  // 秘密（私人路徑）換成佔位值再產生；用到它的變數下面改寫成從環境讀（部署包不含秘密，SDK ADR 0051）
  const site: RelaySiteOptions = siteWithPlaceholders(config.site);
  const privateEnv = privateLaneEnvName(config);
  const readOnlyEnv = readOnlyLanesEnvName(config);
  const files: DeployPackageFile[] = [];
  const add = (path: string, content: string, license: DeployPackageLicense = 'MIT-0') => files.push({ path, content, license });

  add(DEPLOY_CONFIG_FILE, normalizedConfig(config, v));
  if (push) {
    for (const file of renderPushGatewayFiles(config, { sdkVersion: v, embedSdk: embed, dependency, header: (prefix) => header(prefix, v), packageJson: (w) => packageJson(config, dependency, w) })) {
      add(file.path, file.content);
    }
  } else if (worker) {
    const account = config.cloudflare?.accountId;
    add(
      'wrangler.toml',
      renderWranglerToml({
        name,
        main: 'src/entry.mjs',
        compatibilityDate: config.cloudflare?.compatibilityDate ?? DEFAULT_COMPATIBILITY_DATE,
        ...(typeof account === 'string' ? { pinAccountId: account } : {}),
        ...site,
        ...(privateEnv !== undefined || readOnlyEnv !== undefined
          ? {
              secretVars: [
                ...(privateEnv !== undefined ? ['APP_LANES', 'FILE_LANES'] : []),
                ...(readOnlyEnv !== undefined ? ['READONLY_LANES'] : []),
              ],
            }
          : {}),
        header: header('#', v),
      }),
    );
    add('src/entry.mjs', workerEntry(v, selfContained));
    if (selfContained) add('src/relay.mjs', `// SPDX-License-Identifier: AGPL-3.0-only\n// @cinderous/client ${v} 的中繼 Worker（預打包）。Pre-bundled relay Worker; source: ${SDK_SOURCE_REPO}/tree/v${v}\n${ctx.relayWorkerSource!}`, 'AGPL-3.0-only');
    add('package.json', packageJson(config, dependency, true));
    add('.dev.vars.example', devVarsExample(v));
  } else {
    const persist = config.node?.persist === true;
    const trustProxy = config.target === 'docker' ? config.node?.trustProxy === true : true;
    const environment = relayEnvironment({ ...site, persist, trustProxy });
    if (privateEnv !== undefined) {
      // Fly：以 `fly secrets set APP_LANES=…` 設定（fly.toml 會被提交）；compose：從同一個資料夾的 .env 代入，沒設就不啟動
      if (config.target === 'fly') delete environment.APP_LANES;
      else environment.APP_LANES = `\${${privateEnv}:?set ${privateEnv} in .env (private path, SDK ADR 0051)}`;
    }
    if (readOnlyEnv !== undefined) {
      // 唯讀寬限期（SDK ADR 0052）：與私人路徑同一個做法，但沒設＝沒有唯讀車道（不擋啟動）
      if (config.target === 'fly') delete environment.READONLY_LANES;
      else environment.READONLY_LANES = `\${${readOnlyEnv}:-}`;
    }
    add('Dockerfile', renderDockerfile(v, { embedSdk: embed, header: header('#', v) }));
    add('server.mjs', renderServerEntry({ header: header('//', v) }));
    add('package.json', packageJson(config, dependency, false));
    add('.dockerignore', [...header('#', v), renderDockerignore()].join('\n'));
    if (config.target === 'fly') {
      add('fly.toml', renderFlyToml({ name, region: config.fly?.region ?? DEFAULT_FLY_REGION, environment, persist, header: header('#', v) }));
    } else {
      add(
        'docker-compose.yml',
        renderCompose({
          name,
          port: config.node?.port ?? DEFAULT_DOCKER_PORT,
          environment,
          header: header('#', v),
          ...(config.target === 'home-tunnel'
            ? {
                tunnel: {
                  tokenEnv: secretEnvName(config, 'tunnelToken'),
                  ...(config.tunnel?.cloudflaredImage !== undefined ? { image: config.tunnel.cloudflaredImage } : {}),
                },
              }
            : {}),
        }),
      );
    }
  }
  add('.env.example', renderEnvExample(config, v));
  add('.gitignore', renderGitignore(v));
  for (const locale of DEPLOY_GUIDE_LOCALES) {
    add(DEPLOY_GUIDE_FILES[locale], renderDeployGuide(config, locale, { sdkVersion: v, embedSdk: embed, selfContained }));
  }
  add('LICENSE', ctx.licenseText, 'text');
  const mit0 = files.filter((f) => f.license === 'MIT-0').map((f) => f.path);
  add('SOURCE.md', renderSourceMd(config, ctx, embed, selfContained, [...mit0, 'SOURCE.md', GENERATED_MANIFEST]));
  add(GENERATED_MANIFEST, renderManifest(config, v, files, embed));
  return { files, copySdk: embed };
}

/** 檔案內容的 SHA-256（hex）：清單用它判斷檔案有沒有被手改過 */
export function contentHash(content: string): string {
  return bytesToHex(sha256(utf8ToBytes(content)));
}

export interface GeneratedManifest {
  generator: 'cinderous relay build';
  sdk: string;
  target: string;
  /** 路徑 → SHA-256 */
  files: Record<string, string>;
  /** 內嵌的 SDK 資料夾（整個由產生器管理，不逐檔比對） */
  sdkDir?: string;
}

function renderManifest(config: DeployConfig, sdkVersion: string, files: readonly DeployPackageFile[], embed: boolean): string {
  const manifest: GeneratedManifest = {
    generator: 'cinderous relay build',
    sdk: sdkVersion,
    target: config.target,
    files: Object.fromEntries(files.map((f) => [f.path, contentHash(f.content)])),
    ...(embed ? { sdkDir: 'sdk/' } : {}),
  };
  return `${JSON.stringify(manifest, null, 2)}\n`;
}

/**
 * 重新產生前的比對（ADR 0050 §5）：清單裡記錄的檔案，現在的內容跟記錄的雜湊不同＝被手改過。
 * `read(path)` 回傳現在的內容（不存在回 undefined）。回傳被手改過的路徑。
 */
export function modifiedGeneratedFiles(manifestText: string, read: (path: string) => string | undefined): string[] {
  let manifest: GeneratedManifest;
  try {
    manifest = JSON.parse(manifestText) as GeneratedManifest;
  } catch {
    return [GENERATED_MANIFEST];
  }
  const changed: string[] = [];
  for (const [path, hash] of Object.entries(manifest.files ?? {})) {
    const current = read(path);
    if (current !== undefined && contentHash(current) !== hash) changed.push(path);
  }
  return changed;
}

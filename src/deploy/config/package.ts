/** 產生的檔案開頭的授權與來源說明（MIT-0 例外條款；使用者裁示 6） */
function header(prefix: string, sdkVersion: string): string[] {
  return [
    `${prefix} SPDX-License-Identifier: MIT-0`,
    `${prefix} 由 \`cinderous relay build\`（@cinderous/client ${sdkVersion}）依 cinderous.config.json 產生；以 MIT-0 授權（見 SOURCE.md）。SDK 本體是 AGPL-3.0-only。`,
    `${prefix} Generated by \`cinderous relay build\` (@cinderous/client ${sdkVersion}) from cinderous.config.json; MIT-0 (see SOURCE.md). The SDK itself is AGPL-3.0-only.`,
  ];
}

/** 設定檔依固定的鍵順序寫出（同一份設定 → 同一份文字），並記下產生它的 SDK 版號 */
function normalizedConfig(config: DeployConfig, sdkVersion: string): string {
  const order = ['$schema', 'configVersion', 'sdk', 'target', 'service', 'name', 'site', 'node', 'cloudflare', 'fly', 'tunnel', 'pushGateway', 'secrets'] as const;
  const out: Record<string, unknown> = {};
  const withSdk: Record<string, unknown> = { ...config, sdk: sdkVersion };
  for (const key of order) if (withSdk[key] !== undefined) out[key] = withSdk[key];
  return `${JSON.stringify(out, null, 2)}\n`;
}

/** `.env.example`：這個目標會讀的每一個秘密都列出來，值留空 */
function renderEnvExample(config: DeployConfig, sdkVersion: string): string {
  const lines = [...header('#', sdkVersion), '#', '# 複製成 .env 再填值；.env 已在 .gitignore，不要提交。Copy to .env and fill in; .env is git-ignored — never commit it.', ''];
  const host = hostOfTarget(config.target);
  const add = (key: 'cloudflareApiToken' | 'flyApiToken' | 'tunnelToken', note: string) => {
    lines.push(`# ${note}`, `${secretEnvName(config, key)}=`, '');
  };
  if (host === 'worker') {
    add('cloudflareApiToken', 'Cloudflare API Token（沒有就用 `npx wrangler@4 login`）／Cloudflare API token (or use `npx wrangler@4 login`)');
    const account = config.cloudflare?.accountId;
    if (isSecretRef(account)) lines.push('# Cloudflare Account ID', `${account.$env}=`, '');
  }
  if (config.target === 'fly') add('flyApiToken', 'Fly deploy token（`fly tokens create deploy --app <name>`；沒有就用 `fly auth login`）');
  if (config.target === 'home-tunnel') add('tunnelToken', 'Cloudflare Tunnel Token（必填／required）');
  const privateEnv = privateLaneEnvName(config);
  if (privateEnv !== undefined && serviceOfConfig(config) === 'relay') {
    lines.push(
      '# 私人路徑（SDK ADR 0051）：至少 26 字的隨機車道 id，例如 `openssl rand -hex 16`。🔴 它等同密碼。',
      '# Private path (SDK ADR 0051): a random lane id of at least 26 characters, e.g. `openssl rand -hex 16`. 🔴 It is a password.',
      `${privateEnv}=`,
      '',
    );
  }
  const readOnlyEnv = readOnlyLanesEnvName(config);
  if (readOnlyEnv !== undefined && serviceOfConfig(config) === 'relay') {
    lines.push(
      '# 唯讀寬限期（SDK ADR 0052）：換了私人路徑之後的舊路徑，`<舊車道 id>@<到期 unix 秒>`（逗號分隔）。沒有就留空。',
      '# Read-only grace period (SDK ADR 0052): the old path after a change, `<old lane id>@<expiry unix seconds>` (comma-separated). Leave empty if none.',
      `${readOnlyEnv}=`,
      '',
    );
  }
  if (serviceOfConfig(config) === 'push-gateway') {
    lines.push(
      host === 'worker'
        ? '# 推播閘道的執行期秘密：以 `npx wrangler@4 secret put` 上傳（見 README-DEPLOY.md）／runtime secrets, uploaded with `wrangler secret put`'
        : '# 推播閘道的執行期秘密（compose 從這裡代入容器）／runtime secrets (compose passes them into the container)',
      '',
      ...renderPushGatewayEnvLines(config),
    );
  }
  return lines.join('\n');
}

function renderGitignore(sdkVersion: string): string {
  return [...header('#', sdkVersion), '.env', '.env.*', '!.env.example', '.secrets/', '.dev.vars', '*.db', 'node_modules/', '.wrangler/', ''].join('\n');
}

